/**
 * Builds tokens.css, and the plugin's src/lib/design-tokens.ts, from
 * src/tokens/{base,dark,light}.css.
 *
 * Each source file holds one `:root` block of declarations. The output puts
 * them behind the selectors every consumer switches schemes with, so one
 * stylesheet follows the panel (`prefers-color-scheme`, `.color-scheme-*` on
 * `:root`), Web Awesome (`.wa-light` / `.wa-dark`), Starlight
 * (`[data-theme]`) and the design system's own `.theme-light`. They are
 * also declared on `::backdrop`, which inherits nothing from `:root`.
 *
 * design-tokens.ts is the same declarations as strings, renamed into the
 * DevTools' `--lit-devtools-*` namespace. The plugin's lib/ is plain `tsc`
 * output and this package is never published, so the plugin takes a
 * committed copy instead of an import.
 *
 *   node scripts/generate.mjs           # write both files
 *   node scripts/generate.mjs --check   # exit 1 when either is stale
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root = new URL('../', import.meta.url);

/** The declarations inside a token file's single `:root { … }` block. */
const declarations = (name) => {
  const text = readFileSync(new URL(`src/tokens/${name}.css`, root), 'utf8');
  const open = text.indexOf(':root {');
  const close = text.lastIndexOf('}');
  if (open === -1 || close < open) {
    throw new Error(`src/tokens/${name}.css has no :root block`);
  }
  return text.slice(open + ':root {'.length, close).replace(/^\n+|\s+$/g, '');
};

/** Declaration text of each scheme, without selectors. */
export const readTokens = () => ({
  base: declarations('base'),
  dark: declarations('dark'),
  light: declarations('light'),
});

/** Custom property names a block of declarations defines. */
export const definedNames = (text) =>
  new Set(
    [...text.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(--[\w-]+)\s*:/g)].map(
      (m) => m[1]
    )
  );

const varRef = /var\((--[\w-]+)\)/g;

/** Every token's value with `var()` references to other tokens resolved. */
export const resolvedValues = ({base, dark} = readTokens()) => {
  const raw = new Map();
  for (const text of [base, dark]) {
    const clean = text.replace(/\/\*[\s\S]*?\*\//g, '');
    for (const m of clean.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
      raw.set(m[1], m[2].replace(/\s+/g, ' ').trim());
    }
  }
  const resolve = (value) =>
    value.replace(varRef, (ref, name) =>
      raw.has(name) ? resolve(raw.get(name)) : ref
    );
  return new Map([...raw].map(([name, value]) => [name, resolve(value)]));
};

const indent = (text, by) =>
  text
    .split('\n')
    .map((line) => (line ? by + line.replace(/^ {2}/, '') : line))
    .join('\n');

export const renderTokensCss = ({base, dark, light} = readTokens()) => {
  // Only the scheme blocks of this stylesheet say `color-scheme`; the
  // declaration text itself stays free of it, because the DevTools inject
  // that text into pages they don't own.
  dark = `${dark}\n\n  color-scheme: dark;`;
  light = `${light}\n\n  color-scheme: light;`;
  const block = (selector, body, by = '') =>
    `${by}${selector} {\n${indent(body, `${by}  `)}\n${by}}`;
  return `/* Generated by scripts/generate.mjs from src/tokens/*.css. Do not edit. */

${block(':root,\n::backdrop', base)}

/* Dark is the default scheme. */
${block(":root,\n::backdrop,\n.theme-dark,\n.wa-dark,\n:root.color-scheme-dark,\n:root[data-theme='dark']", dark)}

/* Light follows the OS unless something on :root already picked a scheme. */
@media (prefers-color-scheme: light) {
${block(':root:not(.color-scheme-dark, .wa-dark, .theme-dark, [data-theme])', light, '  ')}
}

${block(".theme-light,\n.wa-light,\n:root.color-scheme-light,\n:root[data-theme='light'],\n:root[data-theme='light'] ::backdrop", light)}
`;
};

const devtools = (text) =>
  text.replace(/--(?=[a-z])/g, '--lit-devtools-').replace(/[`\\]/g, '\\$&');

export const renderDesignTokensTs = ({base, dark, light} = readTokens()) =>
  `// Generated by packages/webawesome-theme-lit/scripts/generate.mjs from its
// src/tokens/*.css. Do not edit: change the tokens there and run
// \`pnpm run generate:tokens\`.

/** Theme-agnostic tokens: brand, ink, type, space, radius, elevation, motion. */
export const designBaseCSS = \`
${devtools(base)}
\`;

/** Semantic tokens for the dark scheme (the DevTools theme). */
export const designDarkCSS = \`
${devtools(dark)}
\`;

/** Semantic tokens for the light scheme (the lit.dev website theme). */
export const designLightCSS = \`
${devtools(light)}
\`;
`;

export const outputs = () => [
  {path: fileURLToPath(new URL('tokens.css', root)), text: renderTokensCss()},
  {
    path: fileURLToPath(new URL('../../src/lib/design-tokens.ts', root)),
    text: renderDesignTokensTs(),
  },
];

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const {path, text} of outputs()) {
    if (!check) writeFileSync(path, text);
    else if (readFileSync(path, 'utf8') !== text) {
      console.error(`${path} is stale: run \`pnpm run generate:tokens\``);
      stale = true;
    }
  }
  if (stale) process.exit(1);
}
